#!/usr/bin/env node
/**
 * Deterministic generated reference pages from _data/reference snapshots.
 * Usage:
 *   node scripts/generate-reference.mjs          # write pages
 *   node scripts/generate-reference.mjs --check  # exit 1 if output would change
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(__dirname, "..");
const repo = path.resolve(site, "..");
const data = path.join(repo, "_data/reference");
const check = process.argv.includes("--check");

const BANNER_LINE =
  "# Generated by site/scripts/generate-reference.mjs from _data/reference and docs.lock.yaml. Do not edit.";

function nz(text) {
  return String(text ?? "")
    .replace(/\bOrganization\b/g, "Organisation")
    .replace(/\borganization\b/g, "organisation");
}

function readJson(name) {
  return JSON.parse(fs.readFileSync(path.join(data, name), "utf8"));
}

function pageText(body) {
  const trimmed = body.trim() + "\n";
  if (!trimmed.startsWith("---\n")) {
    throw new Error(`generate-reference: page is missing frontmatter`);
  }
  return `---\n${BANNER_LINE}\n${trimmed.slice(4)}`;
}

function bannerInsideFrontmatter(text) {
  if (!text.startsWith("---\n")) return false;
  const end = text.indexOf("\n---", 4);
  if (end === -1) return false;
  return text.slice(4, end).split("\n").includes(BANNER_LINE);
}

function writePage(rel, body) {
  const dest = path.join(site, "content", rel);
  const next = pageText(body);
  if (check) {
    const prev = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : "";
    if (!bannerInsideFrontmatter(prev)) {
      console.error(`generate-reference: ${rel} banner must be a YAML comment inside frontmatter`);
      process.exitCode = 1;
    }
    if (prev !== next) {
      console.error(`generate-reference: ${rel} is stale`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, next);
}

function escapeCell(value) {
  return String(value ?? "")
    .replace(/\s+/g, " ")
    .replace(/\|/g, "\\|")
    .trim();
}

function mcpPage() {
  const snap = readJson("mcp-tools.json");
  const tools = [...(snap.tools || [])].sort((a, b) => a.name.localeCompare(b.name));
  const groups = new Map();
  for (const t of tools) {
    const g = t.toolset || "other";
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(t);
  }
  const lines = [
    "---",
    "title: MCP tools",
    `description: The ${tools.length} tools on the Talaria MCP server.`,
    "section: reference",
    "order: 40",
    "---",
    "",
    `The official MCP server exposes **${tools.length} tools**. Each tool heading is a stable anchor, for example [\`#search_docs\`](#search_docs).`,
    "",
    "Protocol versions: " + (snap.protocolVersions || []).map((v) => `\`${v}\``).join(", ") + ".",
    "",
    "Connect a client from [MCP and agents](/agents/mcp/). Call a tool from the [CLI](/cli/commands/) with `talaria mcp call <tool>`.",
    "",
  ];
  for (const [group, list] of [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const labels = { ai: "AI", mcp: "MCP", sdk: "SDK", otlp: "OTLP", api: "API" };
    const label = labels[group] || group.charAt(0).toUpperCase() + group.slice(1);
    lines.push(`## ${label}`, "");
    for (const t of list) {
      lines.push(`### ${t.name}`, "");
      if (t.title && t.title !== t.name) lines.push(`**${nz(t.title)}.**`, "");
      if (t.description) lines.push(nz(String(t.description).trim()), "");
      if (t.scope) lines.push(`Scope: \`${t.scope}\`.`, "");
      const params = Array.isArray(t.params) ? t.params : [];
      if (params.length) {
        lines.push("| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |");
        for (const p of params) {
          const name = p.name || "";
          const typ = p.type || "";
          const desc = escapeCell(nz(p.description || p.detail || ""));
          lines.push(`| \`${name}\` | ${typ} | ${p.required ? "yes" : ""} | ${desc} |`);
        }
        lines.push("");
      }
    }
  }
  return lines.join("\n");
}

function errorsPage() {
  const snap = readJson("problem-codes.json");
  const lines = [
    "---",
    "title: Error types",
    "description: RFC 9457 problem types returned by ingest and the organisation API. One anchor per code.",
    "section: reference",
    "order: 35",
    "---",
    "",
    "Ingest and organisation API errors use `application/problem+json`. The `code` field is a stable `lower_snake_case` identifier. The `type` field is an identifier, not a document to fetch, in the form `https://newtalaria.com/docs/reference/errors#<code>`.",
    "",
    "Each heading below is the exact fragment the `type` URL uses (underscores included). Official SDKs branch on `code`. `/otlp` keeps its own error body; see [OTLP](/reference/otlp/).",
    "",
  ];
  for (const c of snap.codes) {
    lines.push(`## ${c.code}`, "");
    if (c.detail) lines.push(nz(c.detail), "");
    lines.push(`\`code\` is \`${c.code}\`. \`type\` ends with \`#${c.code}\`.`, "");
  }
  return lines.join("\n");
}

function openapiPage() {
  const spec = readJson("openapi.json");
  const title = spec.info?.title || "Organisation REST API";
  const version = spec.info?.version || "";
  const server = (spec.servers || [])[0]?.url || "https://api.newtalaria.com";
  const lines = [
    "---",
    "title: Organisation REST API",
    'description: "Read issues, events, traces, logs, and metrics on api.newtalaria.com with an organisation token."',
    "section: reference",
    "order: 30",
    "---",
    "",
    "The organisation REST API is a **read** surface on the control-plane host `https://api.newtalaria.com`. It is not ingest and it is not OTLP. Project API keys (`tal_pk_…`, `tal_sk_…`) and monitor tokens do not work here. Send telemetry to `https://ingest-nz1.newtalaria.com` (native `/v1` or [`/otlp`](/reference/otlp/)) instead.",
    "",
    "## Auth and shape",
    "",
    `- Base URL: \`${server}/api/v1\``,
    "- Auth: `Authorization: Bearer` and an organisation token (`tal_org_<cell>_…`)",
    "- Rate limit: 60 requests per minute",
    "- Errors: RFC 9457 `application/problem+json`, same as ingest — see [Error types](/reference/errors/)",
    "- OpenAPI document: `GET https://api.newtalaria.com/api/v1/openapi.json` — no token required",
    "",
    "```bash",
    "curl -sS https://api.newtalaria.com/api/v1/openapi.json | head",
    "```",
    "",
    "```bash",
    "curl -sS https://api.newtalaria.com/api/v1/organization \\",
    "  -H \"Authorization: Bearer tal_org_nz1_…\"",
    "```",
    "",
    "Mint and revoke organisation tokens in the dashboard. Treat them as secrets.",
    "",
    `This routes table matches the public OpenAPI document${version ? ` (${nz(title)} ${version})` : ""}.`,
    "",
    "## Routes",
    "",
    "| Method | Path | Summary |",
    "| --- | --- | --- |",
  ];
  const paths = spec.paths || {};
  for (const p of Object.keys(paths).sort()) {
    const item = paths[p];
    for (const method of Object.keys(item).sort()) {
      if (["parameters", "servers", "summary", "description", "$ref"].includes(method)) continue;
      const op = item[method] || {};
      lines.push(
        `| ${method.toUpperCase()} | \`${p}\` | ${escapeCell(nz(op.summary || op.description || ""))} |`,
      );
    }
  }
  lines.push(
    "",
    "List endpoints return a page of items and may include `nextCursor`. Query parameters for search and pagination are in the OpenAPI document.",
    "",
    "## Related",
    "",
    "- [Ingest API](/reference/ingest-api/) — project keys, `/v1` write routes",
    "- [OTLP](/reference/otlp/) — OpenTelemetry HTTP ingest",
    "- [Error types](/reference/errors/) — RFC 9457 `code` and `type` anchors",
    "- [MCP](/agents/mcp/) — agent tools on `https://api.newtalaria.com/mcp` (OAuth or a personal token, never an API key)",
    "",
  );
  return lines.join("\n");
}

function cliPage() {
  const snap = readJson("cli-commands.json");
  const lines = [
    "---",
    "title: CLI commands",
    "description: Every talaria command.",
    "section: cli",
    "order: 20",
    "---",
    "",
    "Install from [get.newtalaria.com/cli](https://get.newtalaria.com/cli), then run `talaria version`. See [CLI](/cli/) for install and everyday workflow.",
    "",
    "| Command | What it does |",
    "| --- | --- |",
  ];
  for (const c of snap.commands) {
    lines.push(`| \`${c.use}\` | ${escapeCell(nz(c.short))} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function sdkConfigPage() {
  const snap = readJson("sdk-options.json");
  const lines = [
    "---",
    "title: SDK configuration options",
    "description: Init options for the JavaScript, PHP, Dart, and Flutter SDKs.",
    "section: reference",
    "order: 50",
    "---",
    "",
    "Init options for the official SDKs. Tracing, analytics, replay, flags, and sample rates also come from project policy via `GET /v1/sdk-config`. Leave `url` unset on Talaria Cloud; the SDK derives `https://ingest-<cell>.newtalaria.com` from the key. Cloud OTLP is `https://ingest-nz1.newtalaria.com/otlp`.",
    "",
  ];
  const order = [
    ["javascript", "JavaScript", "/sdk/javascript/configuration/"],
    ["php", "PHP", "/sdk/php/configuration/"],
    ["dart", "Dart", "/sdk/dart/configuration/"],
    ["flutter", "Flutter", "/sdk/flutter/configuration/"],
  ];
  for (const [id, heading, href] of order) {
    const s = snap[id];
    if (!s) continue;
    lines.push(`## ${heading}`, "");
    lines.push(`Package: \`${s.package}\`.`, "");
    lines.push("| Option | Required | Default | Description |", "| --- | --- | --- | --- |");
    const seen = new Set();
    for (const o of s.options) {
      if (seen.has(o.name)) continue;
      seen.add(o.name);
      const def = o.default ? `\`${escapeCell(o.default)}\`` : "";
      lines.push(`| \`${o.name}\` | ${o.required ? "yes" : ""} | ${def} | ${escapeCell(nz(o.detail))} |`);
    }
    lines.push("");
    lines.push(`Full page: [${heading} configuration](${href}).`, "");
  }
  return lines.join("\n");
}

writePage("reference/mcp-tools.md", mcpPage());
writePage("reference/errors.md", errorsPage());
writePage("reference/openapi.md", openapiPage());
writePage("cli/commands.md", cliPage());
writePage("reference/sdk-config.md", sdkConfigPage());

if (check && process.exitCode) {
  console.error("generate-reference: run node site/scripts/generate-reference.mjs and commit the pages");
  process.exit(1);
}
if (!check) console.log("generate-reference: wrote MCP tools, errors, OpenAPI, CLI commands, and SDK options");
